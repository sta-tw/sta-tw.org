ALTER TABLE account_profiles
    ADD COLUMN school_selection_type VARCHAR(24) NOT NULL DEFAULT 'none'
        CHECK (school_selection_type IN ('none', 'directory', 'other_status', 'unlisted')),
    ADD COLUMN school_directory_id UUID REFERENCES account_school_directory(id) ON DELETE RESTRICT;

-- The previous profile picker stored its generic option as the literal
-- "其他". Preserve that intent as the new explicit status selection.
UPDATE account_profiles
SET school_selection_type = 'other_status',
    school_name = '其他（自學／休學／非臺灣學生）'
WHERE lower(btrim(school_name)) = lower('其他')
   OR btrim(school_name) = '其他（自學／休學／非臺灣學生）';

-- Keep existing free-text school values and associate exact known names with
-- the directory. Unmatched names remain available for later curation.
UPDATE account_profiles
SET school_selection_type = 'unlisted'
WHERE btrim(school_name) <> '' AND school_selection_type <> 'other_status';

WITH matches AS (
    SELECT p.account_id, d.id, d.school_name,
        row_number() OVER (
            PARTITION BY p.account_id
            ORDER BY CASE d.school_type WHEN 'university' THEN 0 ELSE 1 END, d.id
        ) AS choice
    FROM account_profiles p
    JOIN account_school_directory d
      ON lower(btrim(d.school_name)) = lower(btrim(p.school_name))
    WHERE p.school_selection_type = 'unlisted'
)
UPDATE account_profiles p
SET school_selection_type = 'directory',
    school_directory_id = matches.id,
    school_name = matches.school_name
FROM matches
WHERE matches.account_id = p.account_id AND matches.choice = 1;

ALTER TABLE account_profiles
    ADD CONSTRAINT account_profiles_school_selection_consistent CHECK (
        (school_selection_type = 'none' AND school_directory_id IS NULL AND btrim(school_name) = '') OR
        (school_selection_type = 'directory' AND school_directory_id IS NOT NULL) OR
        (school_selection_type = 'other_status' AND school_directory_id IS NULL
            AND school_name = '其他（自學／休學／非臺灣學生）') OR
        (school_selection_type = 'unlisted' AND school_directory_id IS NULL AND btrim(school_name) <> '')
    );

CREATE INDEX account_profiles_school_directory_idx
    ON account_profiles (school_directory_id) WHERE school_directory_id IS NOT NULL;
