-- Unified school directory for account profiles. University entries are
-- copied from the admissions master; senior high schools use the MOE 114
-- school-year snapshot (updated 2026-08-12; data.gov.tw dataset 6238).

CREATE TABLE account_school_directory (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    school_type VARCHAR(16) NOT NULL CHECK (school_type IN ('university', 'senior_high')),
    school_name TEXT NOT NULL CHECK (length(btrim(school_name)) BETWEEN 1 AND 120),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX account_school_directory_type_name_unique
    ON account_school_directory (school_type, lower(btrim(school_name)));

CREATE INDEX account_school_directory_active_type_name_idx
    ON account_school_directory (school_type, lower(school_name)) WHERE is_active;

CREATE TRIGGER account_school_directory_set_updated_at
BEFORE UPDATE ON account_school_directory
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

INSERT INTO account_school_directory (school_type, school_name)
SELECT 'university', btrim(school_name)
FROM schools
WHERE btrim(school_name) <> ''
ON CONFLICT DO NOTHING;

